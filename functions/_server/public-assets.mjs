for (const file of PUBLIC_FILES) {
  if (file.endsWith("/index.html")) {
    paths.add("/" + file.slice(0, -10));
    paths.add("/" + file.slice(0, -11));
  } else if (file.endsWith(".html") && file !== "index.html")
    paths.add("/" + file.slice(0, -5));
}
